<?php

namespace App\Features\LacaSeo\Schema\Pro;

use App\Features\LacaSeo\Core\Helper;
use App\Features\LacaSeo\Core\Settings;
use App\Features\LacaSeo\Schema\Db;
use WP_Post;

defined('ABSPATH') || exit;

class VideoSchema
{
    private WP_Post $post;
    private array $urls = [];

    public function __construct(WP_Post $post)
    {
        $this->post = $post;
    }

    public static function detectAndGenerate(WP_Post $post): ?array
    {
        $autodetect = Settings::get("titles.pt_{$post->post_type}_autodetect_video", 'on') === 'on';
        if (!$autodetect) {
            return null;
        }

        $parser = new self($post);
        return $parser->parse();
    }

    public function parse(): ?array
    {
        $content = $this->post->post_content;
        if (empty(trim($content))) {
            return null;
        }

        $videos = [];

        // 1. YouTube iframe / embed / watch / youtu.be
        if (preg_match_all('~(?:https?:)?//(?:www\.)?(?:youtube\.com/(?:watch\?v=|embed/)|youtu\.be/)([a-zA-Z0-9_-]{11})~i', $content, $matches, PREG_SET_ORDER)) {
            foreach ($matches as $m) {
                $id = $m[1];
                if (in_array($id, $this->urls, true)) {
                    continue;
                }
                $this->urls[] = $id;
                $videos[] = [
                    'name'         => '%seo_title%',
                    'description'  => '%seo_description%',
                    'uploadDate'   => '%date(Y-m-d\TH:i:sP)%',
                    'thumbnailUrl' => "https://img.youtube.com/vi/{$id}/maxresdefault.jpg",
                    'embedUrl'     => "https://www.youtube.com/embed/{$id}",
                    'contentUrl'   => "https://www.youtube.com/watch?v={$id}",
                ];
            }
        }

        // 2. Vimeo iframe / player
        if (preg_match_all('~(?:https?:)?//(?:player\.)?vimeo\.com/(?:video/)?([0-9]+)~i', $content, $matches, PREG_SET_ORDER)) {
            foreach ($matches as $m) {
                $id = $m[1];
                if (in_array($id, $this->urls, true)) {
                    continue;
                }
                $this->urls[] = $id;
                $videos[] = [
                    'name'         => '%seo_title%',
                    'description'  => '%seo_description%',
                    'uploadDate'   => '%date(Y-m-d\TH:i:sP)%',
                    'thumbnailUrl' => '%post_thumbnail%',
                    'embedUrl'     => "https://player.vimeo.com/video/{$id}",
                    'contentUrl'   => "https://vimeo.com/{$id}",
                ];
            }
        }

        // 3. WordPress <video src="..."> or [video src="..."]
        if (preg_match_all('~<video[^>]+src=[\'"]([^\'"]+)[\'"]~i', $content, $matches, PREG_SET_ORDER)) {
            foreach ($matches as $m) {
                $src = $m[1];
                if (in_array($src, $this->urls, true)) {
                    continue;
                }
                $this->urls[] = $src;
                $videos[] = [
                    'name'         => '%seo_title%',
                    'description'  => '%seo_description%',
                    'uploadDate'   => '%date(Y-m-d\TH:i:sP)%',
                    'thumbnailUrl' => '%post_thumbnail%',
                    'embedUrl'     => '',
                    'contentUrl'   => $src,
                ];
            }
        }

        if (empty($videos)) {
            return null;
        }

        $schemas = [];
        foreach ($videos as $v) {
            $schemas[] = [
                '@type'            => 'VideoObject',
                'metadata'         => [
                    'title'                   => 'Video',
                    'type'                    => 'template',
                    'shortcode'               => uniqid('s-'),
                    'isPrimary'               => empty(Db::getSchemas($this->post->ID)),
                    'reviewLocationShortcode' => '[laca_seo_rich_snippet]',
                    'category'                => '%categories%',
                    'tags'                    => '%tags%',
                    'isAutoGenerated'         => true,
                ],
                'name'             => $v['name'],
                'description'      => $v['description'],
                'uploadDate'       => $v['uploadDate'],
                'thumbnailUrl'     => $v['thumbnailUrl'],
                'embedUrl'         => $v['embedUrl'],
                'contentUrl'       => $v['contentUrl'],
                'duration'         => '',
                'width'            => '',
                'height'           => '',
                'isFamilyFriendly' => true,
            ];
        }

        return $schemas;
    }
}
